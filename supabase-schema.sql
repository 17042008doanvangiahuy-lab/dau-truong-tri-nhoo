-- Đấu trường trí nhớ: tạo bảng kết quả trong Supabase SQL Editor.
create table if not exists public.memory_scores (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(nickname) between 1 and 24),
  score integer not null check (score between 0 and 600),
  correct_rounds integer not null check (correct_rounds between 0 and 6),
  total_rounds integer not null default 6 check (total_rounds = 6),
  duration_seconds integer not null check (duration_seconds between 1 and 7200),
  created_at timestamptz not null default now()
);

alter table public.memory_scores enable row level security;

-- Cho phép người chơi gửi kết quả và đọc bảng xếp hạng công khai.
-- Lưu ý: đây là chính sách phù hợp cho demo/lớp học, không chống được hoàn toàn việc giả mạo điểm.
drop policy if exists "Public can submit memory scores" on public.memory_scores;
create policy "Public can submit memory scores"
on public.memory_scores for insert
to anon, authenticated
with check (
  char_length(nickname) between 1 and 24
  and score between 0 and 600
  and correct_rounds between 0 and 6
  and total_rounds = 6
  and duration_seconds between 1 and 7200
);

drop policy if exists "Public can view memory leaderboard" on public.memory_scores;
create policy "Public can view memory leaderboard"
on public.memory_scores for select
to anon, authenticated
using (true);

grant select, insert on public.memory_scores to anon, authenticated;
grant usage, select on sequence public.memory_scores_id_seq to anon, authenticated;
